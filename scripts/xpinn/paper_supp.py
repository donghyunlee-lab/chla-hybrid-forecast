          "Median paired difference of the station $R^2$ between the hybrid model and every other model (hybrid minus the model) over the 27 stations, for the forecasts averaged over five seeds. "
          "An asterisk marks $p < 0.05$ (Wilcoxon signed-rank test, not adjusted for the number of comparisons). Rows are ordered by the score of the model with 36-month records.",
