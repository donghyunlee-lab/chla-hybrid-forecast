def paired():
    P = pd.read_csv(RES / "stage7" / "test" / "paired.csv"); P = P[(P.model == "hybrid") & (P.horizon != "mean3_7_14")].assign(horizon=lambda d: d.horizon.astype(int)).set_index(["record", "against", "horizon"])
    order = pd.read_csv(RES / "stage7" / "test" / "more_summary.csv"); order = order[(order.record == 36)].sort_values("median_r2_mean3_7_14", ascending=False).model.tolist()
    order = [m for m in order if m != "hybrid"]; rows = []
    def cell(rec, m, h):
        r = P.loc[(rec, m, h)]; v = f"{r.median_diff:+.3f}"; v = "0.000" if v in ("+0.000", "-0.000") else v.replace("-", "$-$").replace("+", "$+$")
        return v + ("*" if r.wilcoxon_p < 0.05 else "")
    for m in order:
        rows.append(PT.disp(m) + " & " + " & ".join(cell(rec, m, h) for rec in (36, 12) for h in (3, 7, 14)) + " \\\\")
